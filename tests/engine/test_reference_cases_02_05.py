class TestCase05FineAndFees523:
    """Case 01 + fine and fees of CPC art. 523, §1 (10 % each).

    Mechanics confirmed on the official statement: the base of both is the total (A) =
    adjusted + interest; "creditor's amount" = A + fine; "calculation total" = A + fine + fees
    (the fees do not belong to the creditor).

    Known R$ 0.01 divergence: JuriscalcWeb displays 178,599.64 and 194,835.97, values that do
    NOT add up with its own displayed lines (162,363.32 + 16,236.33 = 178,599.65), an effect
    of its internal float64 aggregation. This engine is internally consistent: every total is
    the exact sum of the displayed components (CPC art. 524, I, itemised statement)."""

    def test_gross_total_a(self, total_a_case05):
        assert total_a_case05 == Decimal("162363.32")

    def test_fine_523(self, total_a_case05):
        assert cents(total_a_case05 * Decimal("0.10")) == Decimal("16236.33")

    def test_fee_523(self, total_a_case05):
        assert cents(total_a_case05 * Decimal("0.10")) == Decimal("16236.33")

    def test_creditor_amount_consistent_sum(self, total_a_case05):
        fine = cents(total_a_case05 * Decimal("0.10"))
        assert total_a_case05 + fine == Decimal("178599.65")  # JuriscalcWeb shows .64

    def test_calculation_total_consistent_sum(self, total_a_case05):
        fine = fees = cents(total_a_case05 * Decimal("0.10"))
        assert total_a_case05 + fine + fees == Decimal("194835.98")  # JuriscalcWeb shows .97
