class TestCase04MultipleInstallments:
    """Three installments with different due dates; legal interest from the service of process
    (01/06/2023, later than every due date)."""

    INSTALLMENTS = [
        ("1850.00", "2022-03", "2240.58", "647.05", "2887.63"),
        ("1850.00", "2022-04", "2202.91", "636.17", "2839.08"),
        ("1920.00", "2022-11", "2255.88", "651.47", "2907.35"),
    ]

    def test_legal_pct_since_service(self, repo):
        pct = legal_interest_pct(repo, date(2023, 6, 1), FINAL)
        assert abs(pct6(pct) - Decimal("28.878689")) <= Decimal("0.000001")

    @pytest.mark.parametrize("amount,month,adjusted_ref,interest_ref,total_ref", INSTALLMENTS)
    def test_each_installment(self, repo, amount, month, adjusted_ref, interest_ref, total_ref):
        adjusted = adjust_tjdft(repo, amount, month)
        assert cents(adjusted) == Decimal(adjusted_ref)
        pct = legal_interest_pct(repo, date(2023, 6, 1), FINAL)
        interest = interest_amount(adjusted, pct)
        assert cents(interest) == Decimal(interest_ref)
        assert cents(adjusted + interest) == Decimal(total_ref)

    def test_grand_total(self, repo):
        pct = legal_interest_pct(repo, date(2023, 6, 1), FINAL)
        total = Decimal("0")
        for amount, month, *_ in self.INSTALLMENTS:
            adjusted = adjust_tjdft(repo, amount, month)
            total += cents(adjusted + interest_amount(adjusted, pct))
        assert total == Decimal("8634.06")


